import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {matchesStoryMusicPickerCategory} from "../src/lib/story-music/search.ts";
const qa=JSON.parse(readFileSync("data/story-music-audiodollar-gospel-qa.json","utf8"));
const cat=JSON.parse(readFileSync("data/story-music-authorized-catalog.json","utf8"));
const rights=JSON.parse(readFileSync("data/story-music-rights-records.json","utf8"));
const build=readFileSync("scripts/build.cjs","utf8");
const script=readFileSync("scripts/story-music-audiodollar-one-time-upload.mjs","utf8");
assert.equal(qa.id,"audiodollar-gospel");
assert.equal(qa.license,"CC BY 4.0");
assert.equal(qa.sourceStatesInstrumental,true);
assert.equal(qa.sourceStatesAiGenerated,false);
assert.ok(qa.audio.durationSeconds>60);
assert.match(qa.audio.sha256,/^[a-f0-9]{64}$/);
const track=cat.tracks.find((r:{id:string})=>r.id===qa.id);
const record=rights.records.find((r:{catalogTrackId:string})=>r.catalogTrackId===qa.id);
assert.ok(track && record);
assert.equal(track.audioPath,"story-music://blob/story-music/audio/free-library/audiodollar-gospel.mp3");
assert.ok(track.tags.includes("instrumental-only"));
assert.equal(matchesStoryMusicPickerCategory({...track,provider:"church_authorized",playability:"playable"},"instrumentals"),true);
assert.equal(matchesStoryMusicPickerCategory({...track,provider:"church_authorized",playability:"playable"},"modern_worship"),false);
assert.equal(track.licenseType,"CC BY 4.0");
assert.equal(record.streamingPermitted,true);
assert.equal(record.storagePermitted,true);
assert.doesNotMatch(build,/story-music-audiodollar-one-time-upload.mjs/);
assert.match(script,/sha !== row.audio.sha256/);
console.log("story-music-audiodollar.test.ts OK");
